/**
 * @brief 打印指定长度的分隔线
 * @param c 分隔线使用的字符
 * @param len 分隔线的长度（字符个数）
 *
 * 功能说明:
 *   打印由指定字符组成的水平分隔线，
 *   用于美化输出界面。
 *
 * 输出示例:
 *   printLine('-', 70);
 *   输出: ----------------------------------------------------------------------
 *
 *   printLine('=', 60);
 *   输出: ============================================================
 *
 * 常见用途:
 *   - 包围标题形成醒目边框
 *   - 分隔不同的信息区块
 *   - 表格的上下边框
 *   - 强调重要信息
 *
 * 配合printTitle()使用效果更佳
 */
void printLine(char c, int len) {
    for (int i = 0; i < len; i++) {
        putchar(c);  /* 逐个输出指定字符 */
    }
    putchar('\n');   /* 最后换行 */
}

/**
 * @brief 打印居中显示的标题栏
 * @param title 标题文字
 *
 * 功能说明:
 *   打印带有装饰边框的居中标题。
 *   使界面更加专业和美观。
 *
 * 输出格式:
 *   ============================================================
 *              [居中的标题文字]
 *   ============================================================
 *
 *   总宽度固定为60个字符
 *   标题根据长度自动居中
 *
 * 居中算法:
 *   padding = (60 - 标题长度) / 2
 *   左侧输出padding个空格
 *   然后输出标题文本
 *
 * 使用示例:
 *   printTitle("药品管理系统");
 *   输出:
 *   ============================================================
 *                        药品管理系统
 *   ============================================================
 *
 * 应用场景:
 *   - 各功能模块的主菜单标题
 *   - 子功能的分区标题
 *   - 报表的标题头
 *   - 重要信息的突出显示
 *
 * 注意事项:
 *   - 标题过长时会左偏但不截断
 *   - 中文字符占2个显示宽度但计为1
 *   - 可能导致视觉上不完全居中
 */
void printTitle(const char* title) {
    int len = strlen(title);
    int padding = (60 - len) / 2;  /* 计算左侧填充量 */

    printLine('=', 60);             /* 上边框 */

    /* 输出左侧空格使标题居中 */
    for (int i = 0; i < padding; i++) {
        printf(" ");
    }
    printf("%s\n", title);           /* 标题文字 */

    printLine('=', 60);             /* 下边框 */
}

