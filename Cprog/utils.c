/**
 * @brief 验证日期格式是否合法
 * @param date 待验证的日期字符串
 * @return 合法返回1，非法返回0
 *
 * 功能说明:
 *   检查日期字符串是否符合"YYYY-MM-DD"格式，
 *   并验证日期的实际有效性（如2月30日等）。
 *
 * 格式要求:
 *   - 总长度必须为10个字符
 *   - 第5位和第8位必须是连字符'-'
 *   - 年份: 4位数字，范围1900~2100
 *   - 月份: 2位数字，范围01~12
 *   - 日期: 2位数字，根据月份不同有不同上限
 *
 * 验证步骤:
 *   1. 检查字符串长度是否为10
 *   2. 检查分隔符位置是否正确
 *   3. 解析年、月、日三个整数
 *   4. 检查年月日的合理范围
 *   5. 根据月份检查日期是否超出该月天数
 *   6. 特殊处理闰年的2月份
 *
 * 闰年判断规则:
 *   能被4整除但不能被100整除，或者能被400整除
 *
 * 各月份天数:
 *   - 大月(31天): 1,3,5,7,8,10,12月
 *   - 小月(30天): 4,6,9,11月
 *   - 2月: 平年28天，闰年29天
 *
 * 示例:
 *   "2024-01-15" → 1 (合法)
 *   "2024-02-30" → 0 (2月无30日)
 *   "2024-13-01" → 0 (月份超范围)
 *   "24-01-15"   → 0 (格式错误)
 *
 * 应用场景:
 *   - 入院/出院日期输入验证
 *   - 出生日期验证
 *   - 入职日期验证
 *   - 所有日期字段的格式检查
 */
int isValidDate(const char* date) {
    /* 步骤1: 检查长度 */
    if (strlen(date) != 10) return 0;

    /* 步骤2: 检查分隔符位置 */
    if (date[4] != '-' || date[7] != '-') return 0;

    /* 步骤3: 解析年月日 */
    int year, month, day;
    if (sscanf(date, "%d-%d-%d", &year, &month, &day) != 3) return 0;

    /* 步骤4: 检查基本范围 */
    if (year < 1900 || year > 2100) return 0;
    if (month < 1 || month > 12) return 0;
    if (day < 1 || day > 31) return 0;

    /* 步骤5&6: 检查各月份实际天数 */
    int daysInMonth[] = { 31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31 };

    /* 闰年判断：修改2月天数 */
    if ((year % 4 == 0 && year % 100 != 0) || (year % 400 == 0)) {
        daysInMonth[1] = 29;
    }

    if (day > daysInMonth[month - 1]) return 0;

    return 1;  /* 全部验证通过 */
}

/**
 * @brief 比较两个日期的先后顺序
 * @param date1 第一个日期字符串（格式：YYYY-MM-DD）
 * @param date2 第二个日期字符串（格式：YYYY-MM-DD）
 * @return 比较结果：
 *         -1 表示 date1 < date2（date1较早）
 *          0 表示 date1 == date2（相同日期）
 *          1 表示 date1 > date2（date1较晚）
 *
 * 功能说明:
 *   比较两个日期的时间先后关系。
 *   采用字典序比较法，先比年份，再比月份，最后比日期。
 *
 * 比较算法:
 *   1. 分别解析两个日期的年、月、日
 *   2. 先比较年份，不同则直接返回结果
 *   3. 年份相同则比较月份
 *   4. 月份相同则比较日期
 *   5. 都相同则返回0
 *
 * 使用前提:
 *   两个日期必须是有效的YYYY-MM-DD格式
 *   （建议先用isValidDate()验证）
 *
 * 应用场景:
 *   - 判断出院日期是否晚于入院日期
 *   - 计算住院时长
 *   - 按日期排序记录
 *   - 时间范围查询
 *
 * 示例:
 *   compareDate("2024-01-01", "2024-01-15") → -1
 *   compareDate("2024-06-01", "2024-03-15") → 1
 *   compareDate("2024-05-20", "2024-05-20") → 0
 */
int compareDate(const char* date1, const char* date2) {
    int y1, m1, d1, y2, m2, d2;

    sscanf(date1, "%d-%d-%d", &y1, &m1, &d1);
    sscanf(date2, "%d-%d-%d", &y2, &m2, &d2);

    if (y1 != y2) return (y1 > y2) ? 1 : -1;
    if (m1 != m2) return (m1 > m2) ? 1 : -1;
    if (d1 != d2) return (d1 > d2) ? 1 : -1;

    return 0;  /* 完全相同 */
}

/**
 * @brief 计算两个日期之间的天数差
 * @param date1 起始日期（格式：YYYY-MM-DD）
 * @param date2 结束日期（格式：YYYY-MM-DD）
 * @return 天数差值（date1 - date2的天数）
 *         正数表示date1在date2之后
 *         负数表示date1在date2之前
 *         0表示同一天
 *
 * 功能说明:
 *   利用C标准库的time函数计算两个日期相差的天数。
 *   通过将日期转换为time_t类型再求差实现。
 *
 * 实现原理:
 *   1. 将两个日期字符串分别解析为年、月、日
 *   2. 填充tm结构体（时、分、秒设为0）
 *   3. 调用mktime()将tm转换为time_t（秒级时间戳）
 *   4. 调用difftime()计算秒差
 *   5. 将秒差转换为天数并返回
 *
 * 技术细节:
 *   - mktime()会自动处理时区和夏令时
 *   - difftime()返回double类型的秒差
 *   - 除以86400(24*60*60)得到天数
 *   - 结果截断为整数（舍弃不足一天的部分）
 *
 * 精度说明:
 *   结果精确到整天，小数部分被舍去
 *   例如: 36小时差 → 返回1天
 *
 * 使用前提:
 *   日期格式必须正确且在有效范围内
 *   （建议先用isValidDate()验证）
 *
 * 应用场景:
 *   - 计算患者住院天数
 *   - 计算药品保质期剩余天数
 *   - 计算员工工龄
 *   - 计算设备使用年限
 *
 * 示例:
 *   daysBetween("2024-01-01", "2024-01-10") → 9
 *   daysBetween("2024-01-10", "2024-01-01") → -9
 */
int daysBetween(const char* date1, const char* date2) {
    struct tm tm1 = { 0 }, tm2 = { 0 };
    int y1, m1, d1, y2, m2, d2;

    /* 解析两个日期 */
    sscanf(date1, "%d-%d-%d", &y1, &m1, &d1);
    sscanf(date2, "%d-%d-%d", &y2, &m2, &d2);

    /* 填充第一个tm结构体 */
    tm1.tm_year = y1 - 1900;  /* tm_year是从1900开始的偏移 */
    tm1.tm_mon = m1 - 1;     /* tm_mon是0-11的范围 */
    tm1.tm_mday = d1;

    /* 填充第二个tm结构体 */
    tm2.tm_year = y2 - 1900;
    tm2.tm_mon = m2 - 1;
    tm2.tm_mday = d2;

    /* 转换为time_t时间戳 */
    time_t t1 = mktime(&tm1);
    time_t t2 = mk(&tm2);

    /* 计算秒差并转换为天数 */
    double diff = difftime(t1, t2) / (60 * 60 * 24);
    return (int)diff;
}

/**
 * @brief 获取当前系统日期
 * @param date 用于存储结果的字符数组指针（至少20字节）
 *
 * 功能说明:
 *   获取系统的当前本地日期，格式化为"YYYY-MM-DD"字符串。
 *
 * 输出格式:
 *   固定10字符 + 结束符 = 共11字节
 *   例如: "2024-01-15"
 *
 * 实现原理:
 *   1. 调用time()获取当前时间戳
 *   2. 调用localtime()转换为本地时间结构体
 *   3. 用sprintf()格式化输出
 *
 * 时区说明:
 *   使用的是系统设置的本地时区
 *   不涉及UTC转换问题
 *
 * 使用示例:
 *   char today[20];
 *   getCurrentDate(today);
 *   printf("今天是: %s\n", today);
 *
 * 应用场景:
 *   - 自动设置入院日期
 *   - 记录操作日志的时间戳
 *   - 设置默认日期值
 *   - 计算截止日期
 *
 * 注意事项:
 *   - date指针不能为NULL
 *   - date指向的空间至少要能容纳11字节
 *   - 每次调用都会更新为最新时间
 */
void getCurrentDate(char* date) {
    time_t now = time(NULL);           /* 获取当前时间戳 */
    struct tm* t = localtime(&now);     /* 转换为本地时间 */

    sprintf(date, "%04d-%02d-%02d",
        t->tm_year + 1900,              /* 年份（补零到4位）*/
        t->tm_mon + 1,                  /* 月份（补零到2位）*/
        t->tm_mday);                    /* 日期（补零到2位）*/
}

/**
 * @brief 验证电话号码格式是否合法
 * @param phone 待验证的电话号码字符串
 * @return 合法返回1，非法返回0
 *
 * 功能说明:
 *   检查电话号码是否符合基本格式要求。
 *
 * 验证规则:
 *   1. 长度限制: 7~15个字符
 *   2. 允许的字符:
 *      - 数字 0-9
 *      - 连字符 '-' (用于分隔)
 *      - 空格 ' ' (用于美观)
 *
 * 支持的格式示例:
 *   - "13800138000"        (手机号)
 *   - "010-12345678"       (座机带区号)
 *   - "0755 8888 8888"     (座机带空格)
 *   - "400-800-8888"       (客服热线)
 *   - "(010)12345678"      (带括号) ✗不支持
 *
 * 不支持的格式:
 *   - 含括号 () 的格式
 *   - 含+号的国际号码
 *   - 含字母的分机号
 *
 * 设计考量:
 *   采用宽松验证策略，只检查基本合法性
 *   不做严格的号码段校验
 *   因为号码规则可能变化且因地区而异
 *
 * 应用场景:
 *   - 患者联系电话录入
 *   - 员工手机号登记
 *   - 供应商联系方式
 *   - 紧急联系电话
 */
int isValidPhone(const char* phone) {
    int len = strlen(phone);

    /* 检查长度范围 */
    if (len < 7 || len > 15) return 0;

    /* 逐字符检查合法性 */
    for (int i = 0; i < len; i++) {
        if (!isdigit(phone[i]) && phone[i] != '-' && phone[i] != ' ') {
            return 0;  /* 发现非法字符 */
        }
    }

    return 1;  /* 全部通过 */
}

/**
 * @brief 检查字符串是否为空或纯空白
 * @param str 待检查的字符串指针
 * @return 为空或纯空白返回1，否则返回0
 *
 * 功能说明:
 *   判断字符串是否为以下情况之一：
 *   - NULL指针
 *   - 空字符串 ""
 *   - 只包含空格/制表符的字符串
 *
 * 判定标准:
 *   只要包含至少一个非空白字符即返回0（非空）
 *
 * 空白字符包括:
 *   - 空格 ' '
 *   - 制表符 \t
 *   - 换行符 \n
 *   - 回车符 \r
 *   - 其他isspace()认为的空白字符
 *
 * 使用场景:
 *   - 必填字段验证（如姓名、编号）
 *   - 可选字段判断（决定是否使用默认值）
 *   - 输入后的即时检查
 *
 * 示例:
 *   isEmpty(NULL)        → 1 (空)
 *   isEmpty("")          → 1 (空)
 *   isEmpty("   ")       → 1 (纯空白)
 *   isEmpty(" hello ")   → 0 (非空)
 *   isEmpty("张三")      → 0 (非空)
 */
int isEmpty(const char* str) {
    /* 检查NULL指针和空字符串 */
    if (str == NULL || strlen(str) == 0) return 1;

    /* 检查是否全是空白字符 */
    for (int i = 0; str[i]; i++) {
        if (!isspace((unsigned char)str[i])) {
            return 0;  /* 发现非空白字符 */
        }
    }

    return 1;  /* 全是空白 */
}

/**
 * @brief 去除字符串首尾的空白字符
 * @param str 要处理的字符串（原地修改）
 *
 * 功能说明:
 *   移除字符串开头和结尾的所有空白字符。
 *   在原字符串上直接修改，不分配新内存。
 *
 * 处理的空白字符:
 *   - 空格 ' '
 *   - 制表符 \t
 *   - 换行 \n
 *   - 回车 \r
 *   - 其他isspace()定义的字符
 *
 * 算法步骤:
 *   1. 找到第一个非空白字符的位置(start)
 *   2. 找到最后一个非空白字符的位置(end)
 *   3. 将start到end的部分移到字符串开头
 *   4. 在适当位置添加结束符'\0'
 *
 * 特殊情况处理:
 *   - NULL指针: 直接返回不做处理
 *   - 全空白字符串: 设为空字符串""
 *   - 无需去空格: 保持原样
 *
 * 内存操作:
 *   使用memmove()移动内存块
 *   memmove可以处理源和目标区域重叠的情况
 *
 * 使用示例:
 *   char s[] = "  Hello World  ";
 *   trim(s);  // s变为"Hello World"
 *
 * 性能特点:
 *   时间复杂度O(n)，n为字符串长度
 *   原地操作，无需额外内存分配
 */
void trim(char* str) {
    if (str == NULL) return;

    /* 步骤1: 找到第一个非空白字符 */
    char* start = str;
    while (isspace((unsigned char)*start)) start++;

    /* 检查是否全为空白 */
    if (*start == '\0') {
        str[0] = '\0';
        return;
    }

    /* 步骤2: 找到最后一个非空白字符 */
    char* end = str + strlen(str) - 1;
    while (end > start && isspace((unsigned char)*end)) end--;

    /* 步骤3: 移动有效内容到开头 */
    memmove(str, start, end - start + 1);

    /* 步骤4: 设置新的结束符 */
    str[end - start + 1] = '\0';
}

/**
 * @brief 将字符串转换为大写字母
 * @param str 要转换的字符串（原地修改）
 *
 * 功能说明:
 *   将字符串中的所有小写字母(a-z)转换为大写(A-Z)。
 *   其他字符保持不变。
 *
 * 转换规则:
 *   a-z → A-Z (ASCII码减32)
 *   A-Z → A-Z (不变)
 *   0-9 → 0-9 (不变)
 *   中文 → 中文 (不变)
 *   其他符号 → 不变
 *
 * 处理方式:
 *   原地修改，逐个字符转换
 *   使用标准库函数toupper()
 *
 * 使用场景:
 *   - 统一用户输入的大小写格式
 *   - 比较前标准化（如确认Y/y）
 *   - 代码/编号的大写化显示
 *
 * 示例:
 *   char s[] = "Hello World";
 *   toUpperCase(s);  // s变为"HELLO WORLD"
 *
 * 注意事项:
 *   - 会修改原字符串
 *   - 对于中文等多字节字符不影响
 *   - toupper()需要强制转为unsigned char
 */
void toUpperCase(char* str) {
    for (int i = 0; str[i]; i++) {
        str[i] = toupper((unsigned char)str[i]);
    }
}

/**
 * @brief 生成唯一标识符(ID)
 * @param id 用于存储生成的ID的字符数组（至少25字节）
 * @param prefix ID前缀字符串（用于区分不同类型的ID）
 *
 * 功能说明:
 *   基于当前时间戳和计数器生成唯一ID。
 *   保证在同一次程序运行中不会重复。
 *
 * ID格式:
 *   [前缀][年][月][日][序号]
 *   总长度: prefix长度 + 12位数字
 *
 * 组成部分:
 *   - prefix: 用户指定的前缀（如"MED"、"EMP"等）
 *   - YYYY: 4位年份
 *   - MM: 2位月份（补零）
 *   - DD: 2位日期（补零）
 *   - NNNN: 4位当日序号（从0001开始递增）
 *
 * 生成示例:
 *   prefix="MED", 2024年1月15日第1个
 *   → "MED202401150001"
 *
 *   prefix="EMP", 2024年6月20日第5个
 *   → "EMP202406200005"
 *
 * 唯一性保证:
 *   - 同一天内通过递增序号保证唯一
 *   - 不同天的日期部分自然不同
 *   - 不同前缀用于区分不同实体类型
 *
 * 局限性:
 *   - 序号每天重置（跨天后可能重复）
 *   - 单日最多生成9999个ID
 *   - 程序重启后序号归零
 *
 * 适用场景:
 *   - 药品编号自动生成
 *   - 员工工号自动生成
 *   - 病案编号自动生成
 *   - 各种业务单据编号
 *
 * 前缀建议:
 *   - MED: 药品(Medicine)
 *   - EMP: 员工(Employee)
 *   - REC: 病案(Record)
 *   - OP: 门诊(Outpatient)
 *   - IP: 住院(Inpatient)
 */
void generateID(char* id, const char* prefix) {
    time_t now = time(NULL);           /* 获取当前时间 */
    struct tm* t = localtime(&now);     /* 转换为本地时间 */
    static int counter = 0;             /* 静态计数器 */
    counter++;                          /* 递增计数 */

    /* 拼接各部分生成完整ID */
    sprintf(id, "%s%04d%02d%02d%04d",
        prefix,
        t->tm_year + 1900,              /* 4位年份 */
        t->tm_mon + 1,                  /* 2位月份 */
        t->tm_mday,                     /* 2位日期 */
        counter);                       /* 4位序号 */
}

