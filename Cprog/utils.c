/**
 * @brief 清除输入缓冲区的残留数据
 *
 * 功能说明:
 *   清除标准输入(stdin)缓冲区中的剩余字符。
 *   通常在读取输入后调用，防止残留数据影响后续输入。
 *
 * 使用场景:
 *   - scanf()之后清除换行符
 *   - fgets()读取不完整时清理
 *   - 切换输入方式前的准备工作
 *
 * 实现原理:
 *   循环调用getchar()，直到遇到换行符或文件结束符(EOF)
 *
 * 注意事项:
 *   - 如果缓冲区为空会阻塞等待输入
 *   - 仅在有残留数据时才应调用
 */
void clearInputBuffer() {
    int c;
    while ((c = getchar()) != '\n' && c != EOF);
}

/**
 * @brief 安全的字符串输入函数
 * @param dest 目标字符数组指针（存储输入结果）
 * @param maxLen 目标数组最大容量（含结束符'\0'）
 * @param prompt 输入提示信息（可为NULL或空字符串）
 *
 * 功能说明:
 *   提供安全的字符串输入功能，自动处理：
 *   - 缓冲区溢出保护
 *   - 换行符去除
 *   - 首尾空格去除
 *
 * 输入流程:
 *   1. 显示提示信息prompt
 *   2. 使用fgets()安全读取输入
 *   3. 移除末尾的换行符（如有）
 *   4. 如果输入超长则清空缓冲区
 *   5. 调用trim()去除首尾空格
 *
 * 安全机制:
 *   - fgets()自带长度限制，不会溢出
 *   - maxLen参数控制最大读取长度
 *   - 自动添加字符串结束符'\0'
 *
 * 使用示例:
 *   char name[50];
 *   safeInput(name, sizeof(name), "请输入姓名: ");
 *
 * 注意事项:
 *   - dest必须有足够空间(maxLen字节)
 *   - prompt可以为空字符串""（仅换行）
 *   - 输入结果不含首尾空白字符
 */
void safeInput(char* dest, int maxLen, const char* prompt) {
    printf("%s", prompt);

    if (fgets(dest, maxLen, stdin) != NULL) {
        size_t len = strlen(dest);

        /* 移除末尾的换行符 */
        if (len > 0 && dest[len - 1] == '\n') {
            dest[len - 1] = '\0';
        }
        else {
            /* 输入过长，清空缓冲区剩余部分 */
            clearInputBuffer();
        }

        /* 去除首尾空格 */
        trim(dest);
    }
}

/**
 * @brief 安全的整数输入函数
 * @param prompt 输入提示信息
 * @return 用户输入的整数值
 *
 * 功能说明:
 *   从标准输入读取一个整数，具有以下特点：
 *   - 循环验证直到输入有效整数
 *   - 对非法输入给出明确错误提示
 *   - 自动跳过无效字符
 *
 * 实现原理:
 *   1. 先用fgets()读取整行输入到缓冲区
 *   2. 用sscanf()尝试解析整数
 *   3. 解析失败则提示并重新输入
 *   4. 成功则返回解析结果
 *
 * 验证规则:
 *   - 必须能解析出至少一个整数
 *   - 允许前后有空格
 *   - 允许后面有额外字符（只取第一个整数）
 *
 * 错误处理:
 *   - 输入非数字: 提示"输入无效，请重新输入整数！"
 *   - 空输入: 同样视为无效
 *
 * 使用示例:
 *   int age = inputInt("请输入年龄: ");
 *   int choice = inputInt("请选择(1-5): ");
 *
 * 返回值范围:
 *   取决于int类型的取值范围
 *   典型系统: -2147483648 ~ 2147483647
 */
int inputInt(const char* prompt) {
    int value;
    char buffer[100];  /* 输入缓冲区 */

    while (1) {
        printf("%s", prompt);

        if (fgets(buffer, sizeof(buffer), stdin) != NULL) {

            /* 尝试从缓冲区解析整数 */
            if (sscanf(buffer, "%d", &value) == 1) {
                return value;  /* 解析成功，返回值 */
            }
        }

        /* 解析失败，提示重新输入 */
        printf("输入无效，请重新输入整数！\n");
    }
}

/**
 * @brief 安全的浮点数输入函数
 * @param prompt 输入提示信息
 * @return 用户输入的浮点数值
 *
 * 功能说明:
 *   从标准输入读取一个浮点数(double类型)，特点：
 *   - 循环验证直到输入有效数字
 *   - 支持整数和小数两种形式
 *   - 支持科学计数法表示
 *
 * 与inputInt的区别:
 *   - 返回double而非int
 *   - 接受小数点和指数符号
 *   - 用于金额、比例等需要精度的场合
 *
 * 支持的输入格式:
 *   - "123"        → 123.0
 *   - "45.67"      → 45.67
 *   - "-3.14"      → -3.14
 *   - "2.5e3"      → 2500.0
 *   - "  100  "    → 100.0（忽略前后空格）
 *
 * 错误处理:
 *   - 非法字符: 提示"输入无效，请重新输入数字！"
 *   - 空输入: 视为无效
 *
 * 使用示例:
 *   double price = inputDouble("请输入价格: ");
 *   double salary = inputDouble("请输入工资: ");
 *
 * 应用场景:
 *   - 药品价格输入
 *   - 医疗费用录入
 *   - 工资/奖金设置
 *   - 百分比/比率输入
 */
double inputDouble(const char* prompt) {
    double value;
    char buffer[100];  /* 输入缓冲区 */

    while (1) {
        printf("%s", prompt);

        if (fgets(buffer, sizeof(buffer), stdin) != NULL) {

            /* 尝试从缓冲区解析浮点数 */
            if (sscanf(buffer, "%lf", &value) == 1) {
                return value;  /* 解析成功，返回值 */
            }
        }

        /* 解析失败，提示重新输入 */
        printf("输入无效，请重新输入数字！\n");
    }
}

