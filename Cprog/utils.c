/**
 * @brief 要求用户确认操作
 * @param message 确认提示信息
 * @return 用户确认(Y/y)返回1，否则返回0
 *
 * 功能说明:
 *   显示确认消息并等待用户输入Y或N。
 *   用于危险操作的二次确认。
 *
 * 显示格式:
 *   "[message] (Y/N): "
 *   然后等待用户输入
 *
 * 判断逻辑:
 *   - 输入以'Y'或'y'开头 → 返回1（确认）
 *   - 输入以'N'或'n'开头 → 返回0（取消）
 *   - 空输入 → 返回0并提示
 *   - 其他 → 返回0
 *
 * 输入处理:
 *   - 只检查第一个字符
 *   - 忽略后续字符
 *   - 不区分大小写
 *
 * 使用场景:
 *   - 删除操作前的确认
 *   - 重要数据修改前的确认
 *   - 不可逆操作前的确认
 *   - 清空数据的确认
 *
 * 示例:
 *   if (confirm("确定要删除此记录吗")) {
 *       // 执行删除
 *   } else {
 *       // 取消操作
 *   }
 */
int confirm(const char* message) {
    char choice[10];

    printf("%s (Y/N): ", message);
    safeInput(choice, sizeof(choice), "");

    /* 空输入处理 */
    if (strlen(choice) == 0) {
        printf("请输入 Y 或 N\n");
        return 0;
    }

    /* 检查第一个字符是否为Y/y */
    return (choice[0] == 'Y' || choice[0] == 'y');
}

